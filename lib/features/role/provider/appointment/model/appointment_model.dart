class AppointmentModel {
  final String avatarUrl;
  final String name;
  final String service;
  final String time;
  final String date;
  final String status;
  final String amount;

  AppointmentModel({
    required this.avatarUrl,
    required this.name,
    required this.service,
    required this.time,
    required this.date,
    required this.status,
    required this.amount,
  });
}
